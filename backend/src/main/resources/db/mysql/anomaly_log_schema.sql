CREATE TABLE IF NOT EXISTS anomaly_logs (
    id BIGINT NOT NULL AUTO_INCREMENT,
    anomaly_key VARCHAR(120) NOT NULL,
    rule_code VARCHAR(60) NOT NULL,
    severity VARCHAR(20) NOT NULL,
    title VARCHAR(160) NOT NULL,
    summary VARCHAR(500) NOT NULL,
    source_type VARCHAR(40) NOT NULL,
    source_id VARCHAR(80) NULL,
    source_label VARCHAR(160) NOT NULL,
    payload_json LONGTEXT NULL,
    active BIT(1) NOT NULL DEFAULT b'1',
    status VARCHAR(30) NOT NULL DEFAULT 'OPEN',
    first_detected_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_detected_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at DATETIME NULL,
    reviewed_by VARCHAR(100) NULL,
    review_note VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_anomaly_logs_anomaly_key (anomaly_key),
    KEY idx_anomaly_logs_status_active (status, active),
    KEY idx_anomaly_logs_severity_active (severity, active),
    KEY idx_anomaly_logs_last_detected_at (last_detected_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

